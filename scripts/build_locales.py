LOCALE_INDEX = {"en": 0, "ru": 1, "ky": 2}


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    bad = [key for key, values in STRINGS.items() if len(values) != 3 or not all(values)]
    if bad:
        print("Incomplete translations for: " + ", ".join(bad), file=sys.stderr)
        return 1

    for locale, index in LOCALE_INDEX.items():
        payload = {key: values[index] for key, values in STRINGS.items()}
        path = OUT_DIR / f"{locale}.json"
        path.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        print(f"wrote {path.relative_to(OUT_DIR.parent.parent)} ({len(payload)} keys)")
    return 0


